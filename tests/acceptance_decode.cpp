#include "../src/acceptance_trace.cpp"
#include <cassert>
int main() {
    std::vector<unsigned char> image(8192);
    auto dos = reinterpret_cast<IMAGE_DOS_HEADER*>(image.data()); dos->e_magic = IMAGE_DOS_SIGNATURE; dos->e_lfanew = 128;
    auto nt = reinterpret_cast<IMAGE_NT_HEADERS32*>(image.data()+128);
    nt->FileHeader.NumberOfSections = 1; nt->FileHeader.SizeOfOptionalHeader = sizeof(IMAGE_OPTIONAL_HEADER32); nt->OptionalHeader.SizeOfImage = 8192;
    auto section = IMAGE_FIRST_SECTION(nt); section->VirtualAddress = 1024; section->Misc.VirtualSize = 4096; section->Characteristics = IMAGE_SCN_MEM_EXECUTE;
    const unsigned char fixture[] = {0xE8,0x66,0xB9,0xFF,0xFF,0x84,0xC0,0x75,0x63,0x8B,0x0D,0x24,0x56,0xBB,0x01,0x6A,0x01,0xE8,0x15,0x0C,0x39,0x00,0x84,0xC0,0x75,0x52,0x8B,0x0D,0x24,0x56,0xBB,0x01,0x6A,0x02,0xE8,0x04,0x0C,0x39,0x00,0x84,0xC0,0x75,0x41,0xA2,0x36,0x0C,0x16,0x01,0xC6,0x05,0x35,0x0C,0x16,0x01,0x01,0xA2,0xBC,0xF4,0x18,0x01,0xE8,0x0A,0xBA,0xFF,0xFF,0xC7,0x05,0x40,0x0C,0x16,0x01,0x32,0x00,0x00,0x00,0xC7,0x05,0xA8,0x0B,0x03,0x01,0xFF,0xFF,0xFF,0xFF,0x80,0x3D,0x18,0x15,0x16,0x01,0x00,0x0F,0x85,0x1F,0x24,0x00,0x00,0xE8,0xE4,0xB9,0xFF,0xFF,0xE9,0x15,0x24,0x00,0x00,0xC6,0x05,0x36,0x0C,0x16,0x01,0x01,0xC6,0x05,0xA7,0x6D,0x8B,0x01,0x01,0xC6,0x05,0xBC,0xF4,0x18,0x01};
    auto install = [&](unsigned offset) {
        auto code = image.data()+offset; memcpy(code, fixture, sizeof(fixture)); auto site = code+48;
        const auto first = static_cast<DWORD>(reinterpret_cast<std::uintptr_t>(image.data()+6000));
        const DWORD second = first+1, page = first+16;
        auto rel = static_cast<std::int32_t>((image.data()+5000)-(site+17));
        memcpy(site+2, &first, 4); memcpy(site-4, &second, 4); memcpy(site+19, &page, 4); memcpy(site+13, &rel, 4);
    };
    install(1300);
    assert(FindAcceptance(image.data()));
    assert(acceptance.first == image.data()+6000 && acceptance.second == image.data()+6001);
    assert(acceptance.prepare == image.data()+5000);
    assert(reinterpret_cast<unsigned char*>(acceptance.page) == image.data()+6016);
    install(1800); assert(!FindAcceptance(image.data()));
    memset(image.data()+1800, 0, sizeof(fixture));
    image[1300+48+6] = 0; assert(!FindAcceptance(image.data()));
    return 0;
}
