#include <windows.h>
#include <d3dcompiler.h>
#include <cstdio>
#include <cstring>
int main(){
    const char* source=R"(
sampler2D frame : register(s0);
float4 stepSize : register(c0);
float4 main(float2 uv:TEXCOORD0):COLOR0 {
    float3 color=tex2D(frame,uv).rgb*0.2270270270;
    color+=(tex2D(frame,uv+stepSize.xy*1.3846153846).rgb+tex2D(frame,uv-stepSize.xy*1.3846153846).rgb)*0.3162162162;
    color+=(tex2D(frame,uv+stepSize.xy*3.2307692308).rgb+tex2D(frame,uv-stepSize.xy*3.2307692308).rgb)*0.0702702703;
    return float4(color,1);
})";
    ID3DBlob* shader=nullptr;ID3DBlob* errors=nullptr;
    const HRESULT hr=D3DCompile(source,std::strlen(source),"pause blur",nullptr,nullptr,"main","ps_2_0",D3DCOMPILE_OPTIMIZATION_LEVEL3,0,&shader,&errors);
    if(FAILED(hr)){if(errors){std::fwrite(errors->GetBufferPointer(),1,errors->GetBufferSize(),stderr);errors->Release();}return 1;}
    FILE* file=nullptr;if(fopen_s(&file,"src/pause_blur_shader.hpp","w")!=0||!file){shader->Release();return 2;}
    std::fprintf(file,"#pragma once\n// Generated by tools/compile-pause-blur.cpp; no runtime compiler dependency.\nconstexpr DWORD pauseBlurShader[]={\n");
    const auto words=static_cast<const DWORD*>(shader->GetBufferPointer());
    for(SIZE_T i=0;i<shader->GetBufferSize()/sizeof(DWORD);++i)std::fprintf(file,"0x%08lXu,%s",words[i],(i%8==7)?"\n":"");
    std::fprintf(file,"\n};\n");std::fclose(file);shader->Release();if(errors)errors->Release();return 0;
}
